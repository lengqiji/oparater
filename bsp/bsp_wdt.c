uint8_t wdt_init_flag = 0;


//初始化
void wdt_init(void)
{
    stc_wdt_init_t stcWdtInit;

    /* configure structure initialization */
    MEM_ZERO_STRUCT(stcWdtInit);

	//PCLK3:50MHz
    stcWdtInit.enClkDiv = WdtPclk3Div1024;
    stcWdtInit.enCountCycle = WdtCountCycle65536;//65536/(50000000/1024) = 1.3S
    stcWdtInit.enRefreshRange = WdtRefresh0To100Pct;
    stcWdtInit.enSleepModeCountEn = Disable;
    stcWdtInit.enRequestType = WdtTriggerResetRequest;
    WDT_Init(&stcWdtInit);

	/* First refresh to start WDT */
    WDT_RefreshCounter();
    /* Wait for WDT module to complete initial load */
    //Ddl_Delay1ms(200u);
}

//喂狗
void wdt_feed(void)
{
    WDT_RefreshCounter();
}

